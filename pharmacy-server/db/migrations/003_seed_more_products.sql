  sp.name,
  sp.description,
  c.id,
  cl.id,
  sp.unit,
  sp.packaging_unit,
  sp.purchase_price,
  sp.sale_price,
  sp.expiry_date,
  sp.quantity
FROM seeded_products sp
JOIN categories c ON c.name = sp.category_name
JOIN product_classes cl ON cl.name = sp.class_name AND cl.category_id = c.id
WHERE NOT EXISTS (
  SELECT 1 FROM products p WHERE p.name = sp.name
);